using System;

namespace Combat.ProceduralGeneration
{
    public enum CombatClass
    {
        Striker,    // Страйкер: постоянный высокий урон, хрупкий, мобильный (D&D 4e)
        Tank,       // Танк: фокус внимания на себе, защита союзников, удержание проходов
        Leader,     // Лидер (Саппорт): баффы, лечение союзников, координация тыла
        Controller  // Контроллер: манипуляция полем боя, ловушки, срыв темпа игрока
    }

    public enum CombatArchetype
    {
        Assassin,   // Убийца (Страйкер): быстрый урон из слепой зоны, отступление при опасности
        Bodyguard,  // Телохранитель (Танк): прикрывает собой уязвимых союзников, тяжелый блок
        Medic,      // Медик (Лидер): держится в тылу, исцеляет раненых соратников
        Trapper     // Траппер (Контроллер): расставляет препятствия/ловушки, кайтит игрока
    }

    public enum EnemyVector
    {
        World,      // Мир (W): рельеф, платформы, акробатика, мобильность
        Player,     // Игрок (P): терпеливость, упреждение действий игрока
        Allies,     // Свои (N): эмпатия, прикрытие, субординация (активно при N >= 2)
        Self        // Я (S): самосохранение, гордость, мастерство парирования
    }
}
